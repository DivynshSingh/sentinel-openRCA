-- ============================================================
-- Sentinel DuckDB Schema
-- Based on locked architecture: Raw Telemetry + Processed Evidence + Reasoning State
-- ============================================================

-- === RAW TELEMETRY (loaded from OpenRCA CSVs) ===

CREATE TABLE IF NOT EXISTS component (
    cmdb_id VARCHAR PRIMARY KEY,
    name VARCHAR NOT NULL,
    type VARCHAR NOT NULL,         -- pod|service|node|container
    system VARCHAR NOT NULL        -- Bank|Telecom|Market
);

CREATE TABLE IF NOT EXISTS metric_point (
    id VARCHAR PRIMARY KEY,
    component_id VARCHAR NOT NULL,
    kpi_name VARCHAR NOT NULL,
    ts TIMESTAMP NOT NULL,
    value DOUBLE NOT NULL,
    is_anomalous BOOLEAN DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_metric_component ON metric_point(component_id);
CREATE INDEX IF NOT EXISTS idx_metric_ts ON metric_point(ts);
CREATE INDEX IF NOT EXISTS idx_metric_kpi ON metric_point(kpi_name);

CREATE TABLE IF NOT EXISTS span (
    span_id VARCHAR PRIMARY KEY,
    trace_id VARCHAR NOT NULL,
    parent_span_id VARCHAR,
    component_id VARCHAR NOT NULL,
    start_time TIMESTAMP NOT NULL,
    duration_ms INTEGER NOT NULL,
    status VARCHAR NOT NULL,
    call_type VARCHAR
);
CREATE INDEX IF NOT EXISTS idx_span_trace ON span(trace_id);
CREATE INDEX IF NOT EXISTS idx_span_parent ON span(parent_span_id);
CREATE INDEX IF NOT EXISTS idx_span_component ON span(component_id);
CREATE INDEX IF NOT EXISTS idx_span_start ON span(start_time);

CREATE TABLE IF NOT EXISTS log_entry (
    id VARCHAR PRIMARY KEY,
    component_id VARCHAR NOT NULL,
    ts TIMESTAMP NOT NULL,
    level VARCHAR NOT NULL,
    message VARCHAR NOT NULL,
    template_id VARCHAR
);
CREATE INDEX IF NOT EXISTS idx_log_component ON log_entry(component_id);
CREATE INDEX IF NOT EXISTS idx_log_ts ON log_entry(ts);
CREATE INDEX IF NOT EXISTS idx_log_level ON log_entry(level);

-- === PROCESSED EVIDENCE (generated by Data Processor) ===

CREATE TABLE IF NOT EXISTS metric_anomaly (
    id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    component_id VARCHAR NOT NULL,
    metric_name VARCHAR NOT NULL,
    anomaly_pattern VARCHAR NOT NULL,   -- spike|steady_rise|level_shift
    ts TIMESTAMP NOT NULL,
    deviation_score DOUBLE NOT NULL     -- k-sigma
);
CREATE INDEX IF NOT EXISTS idx_ma_query ON metric_anomaly(query_id);
CREATE INDEX IF NOT EXISTS idx_ma_component ON metric_anomaly(component_id);

CREATE TABLE IF NOT EXISTS trace_summary (
    id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    callee_id VARCHAR NOT NULL,
    window_start TIMESTAMP NOT NULL,
    window_end TIMESTAMP NOT NULL,
    total_calls INTEGER NOT NULL,
    max_latency_ms INTEGER NOT NULL,
    caller_distribution JSON            -- {caller_id: count, ...}
);
CREATE INDEX IF NOT EXISTS idx_ts_query ON trace_summary(query_id);
CREATE INDEX IF NOT EXISTS idx_ts_callee ON trace_summary(callee_id);

CREATE TABLE IF NOT EXISTS trace_path (
    id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    grandparent_id VARCHAR,
    caller_id VARCHAR NOT NULL,
    callee_id VARCHAR NOT NULL,
    frequency INTEGER NOT NULL,
    is_high_latency BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tp_query ON trace_path(query_id);

CREATE TABLE IF NOT EXISTS log_summary (
    id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    component_id VARCHAR NOT NULL,
    template_id VARCHAR NOT NULL,
    template_text VARCHAR NOT NULL,
    tfidf_score DOUBLE NOT NULL,
    rank_pct INTEGER NOT NULL,
    earliest_ts TIMESTAMP NOT NULL,
    level VARCHAR NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ls_query ON log_summary(query_id);
CREATE INDEX IF NOT EXISTS idx_ls_component ON log_summary(component_id);

-- === QUERY & REASONING STATE ===

CREATE TABLE IF NOT EXISTS query (
    query_id VARCHAR PRIMARY KEY,
    question_text VARCHAR NOT NULL,
    window_start TIMESTAMP NOT NULL,
    window_end TIMESTAMP NOT NULL,
    system VARCHAR NOT NULL,
    status VARCHAR DEFAULT 'pending',   -- pending|processing|done|error
    ground_truth JSON                   -- from query.csv, for eval
);
CREATE INDEX IF NOT EXISTS idx_query_status ON query(status);

CREATE TABLE IF NOT EXISTS hypothesis (
    hypothesis_id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    component_id VARCHAR NOT NULL,
    phase_created VARCHAR NOT NULL,     -- p1_metrics|p2_logs|p3_verify
    reason VARCHAR NOT NULL,
    confidence DOUBLE,
    status VARCHAR DEFAULT 'active',    -- active|dropped|confirmed
    superseded_by VARCHAR,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_hypo_query ON hypothesis(query_id);
CREATE INDEX IF NOT EXISTS idx_hypo_status ON hypothesis(status);

CREATE TABLE IF NOT EXISTS hypothesis_evidence (
    evidence_id VARCHAR PRIMARY KEY,
    hypothesis_id VARCHAR NOT NULL,
    evidence_type VARCHAR NOT NULL,     -- metric_anomaly|trace_summary|log_summary|span|raw_metric|raw_log
    evidence_table VARCHAR NOT NULL,
    evidence_pk VARCHAR NOT NULL,
    citation_text VARCHAR
);
CREATE INDEX IF NOT EXISTS idx_he_hypo ON hypothesis_evidence(hypothesis_id);

CREATE TABLE IF NOT EXISTS finding (
    finding_id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    hypothesis_id VARCHAR,
    root_cause_time TIMESTAMP,
    root_cause_component VARCHAR,
    root_cause_reason VARCHAR,
    confirmed_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_find_query ON finding(query_id);

CREATE TABLE IF NOT EXISTS agent_step (
    step_id VARCHAR PRIMARY KEY,
    query_id VARCHAR NOT NULL,
    phase VARCHAR NOT NULL,             -- p0|p1|p2|p3|p4
    tool_name VARCHAR NOT NULL,
    args JSON,
    result_summary VARCHAR,
    ts TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_step_query ON agent_step(query_id);
